class Command(BaseCommand):
    help = 'Заполняет типы тестов и демонстрационные вопросы (без изменения схемы БД)'

    def handle(self, *args, **options):
        admin_user = User.objects.filter(is_staff=True).first()
        if not admin_user:
            admin_user = User.objects.first()
        if not admin_user:
            self.stdout.write(self.style.ERROR('Нет пользователей. Создайте администратора.'))
            return

        for type_name, desc in [
            ('Обычный', 'Тренировочный режим — 20 случайных вопросов'),
            ('Экзамен', 'Режим экзамена'),
            ('Марафон', 'Марафон на 400 вопросов'),
            ('Игра', 'Игровой режим'),
        ]:
            Types.objects.get_or_create(type_name=type_name, defaults={'description': desc})

        created = 0
        for text, right, wrong in SAMPLE_QUESTIONS:
            if Bank_questions.objects.filter(question_text=text).exists():
                continue
            Bank_questions.objects.create(
                question_text=text,
                right_answer=right,
                incorrect_answers=pack_incorrect_answers(wrong),
                admin=admin_user,
            )
            created += 1

        total = Bank_questions.objects.count()
        self.stdout.write(self.style.SUCCESS(f'Добавлено вопросов: {created}. Всего в банке: {total}.'))
